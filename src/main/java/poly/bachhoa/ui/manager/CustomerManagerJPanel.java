    private void loadTableFromList() {
        model.setRowCount(0);
        for (KhachHang kh : listKH) {
            model.addRow(new Object[]{
                kh.getMaKH(),
                kh.getTenKH(),
                kh.getDienThoai()
            });
        }
    }

    private void initTable() {
        model = (DefaultTableModel) tbQLKH.getModel();
        model.setColumnIdentifiers(new Object[]{"Mã KH", "Họ tên", "Điện thoại"});
//  
    }

    private void loadTable() {
        listKH = khDAO.selectAll(); // lấy tất cả khách hàng
        totalPage = (int) Math.ceil((double) listKH.size() / pageSize);
        loadPage(pageIndex);
    }

    private void loadPage(int page) {
        model.setRowCount(0); // xóa bảng
        int start = page * pageSize;
        int end = Math.min(start + pageSize, listKH.size());
        for (int i = start; i < end; i++) {
            KhachHang kh = listKH.get(i);
            model.addRow(new Object[]{
                kh.getMaKH(),
                kh.getTenKH(),
                kh.getDienThoai()
            });
        }
        lblStep.setText((page + 1) + "");
        lbStepCount.setText("" + totalPage);
        updateNavigationButtons();
    }

    private void updateNavigationButtons() {
        btnFirst.setEnabled(pageIndex > 0); // bật nút << nếu không phải trang đầu
        btnPrev.setEnabled(pageIndex > 0);  // bật nút < nếu không phải trang đầu
        btnNext.setEnabled(pageIndex < totalPage - 1); // bật nút > nếu không phải trang cuối
        btnLast.setEnabled(pageIndex < totalPage - 1);  // bật nút >> nếu không phải trang cuối
    }

    private void showDetail(int idx) {
        if (idx < 0 || idx >= listKH.size()) {
            return;
        }
        KhachHang kh = listKH.get(idx);
        txtMaKH.setText(kh.getMaKH());
        txtTenKH.setText(kh.getTenKH());

        txtDienThoai.setText(kh.getDienThoai());

    }

    private void selectRow(int r) {
        if (r >= 0 && r < tbQLKH.getRowCount()) {
            row = r;
            String maKH = tbQLKH.getValueAt(row, 0).toString();
            KhachHang kh = khDAO.selectById(maKH);
            setForm(kh);
            lblStep.setText((row + 1) + "");
        }
    }

    private void setForm(KhachHang kh) {
        txtMaKH.setText(kh.getMaKH());
        txtTenKH.setText(kh.getTenKH());

        txtDienThoai.setText(kh.getDienThoai());

    }

    private void clearForm() {
        txtMaKH.setText("");
        txtTenKH.setText("");

        txtDienThoai.setText("");

        row = -1;
    }

