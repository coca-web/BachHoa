    private void btnLocActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLocActionPerformed
           String ma = txtLoc.getText().trim(); // loại bỏ khoảng trắng đầu/cuối

    // 1. Validate: phải nhập từ khóa
    if (ma.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Vui lòng nhập từ khóa để lọc!", "Thông báo", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. Lọc dữ liệu
    listKH = khDAO.selectByKeyword(ma);

    // 3. Hiển thị lên JTable
    model.setRowCount(0); // xóa dữ liệu cũ
    for (KhachHang kh : listKH) {
        model.addRow(new Object[]{
            kh.getMaKH(),
            kh.getTenKH(),
            kh.getDienThoai()
        });
    }

    // 4. Thông báo kết quả
    if (listKH.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Không tìm thấy khách hàng nào phù hợp.", "Kết quả lọc", JOptionPane.INFORMATION_MESSAGE);
    } else {
        JOptionPane.showMessageDialog(this, "Đã tìm thấy " + listKH.size() + " khách hàng.", "Kết quả lọc", JOptionPane.INFORMATION_MESSAGE);
    }
    }//GEN-LAST:event_btnLocActionPerformed

