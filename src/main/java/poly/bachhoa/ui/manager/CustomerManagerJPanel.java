    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        // TODO add your handling code here:
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn khách hàng để sửa!");
            return;
        }

        String maKH = txtMaKH.getText().trim();
        String tenKH = txtTenKH.getText().trim();

        String dienThoai = txtDienThoai.getText().trim();

        if (maKH.isEmpty() || tenKH.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mã khách hàng và Họ tên không được để trống!");
            return;
        }

        KhachHang kh = new KhachHang(maKH, tenKH, dienThoai);

        if (khDAO.update(kh)) {
            JOptionPane.showMessageDialog(this, "Cập nhật thành công!");
            loadTable();
            // chọn lại dòng vừa sửa
            tbQLKH.setRowSelectionInterval(row, row);
            showDetail(row);
        } else {
            JOptionPane.showMessageDialog(this, "Cập nhật thất bại!");
        }
    }//GEN-LAST:event_btnSuaActionPerformed

