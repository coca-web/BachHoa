    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        // TODO add your handling code here:

        String maKH = txtMaKH.getText().trim();
        String tenKH = txtTenKH.getText().trim();

        String dienThoai = txtDienThoai.getText().trim();

        if (maKH.isEmpty() || tenKH.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mã khách hàng và Họ tên không được để trống!");
            return;
        }

        if (!dienThoai.matches("\\d{0,10}")) {
            JOptionPane.showMessageDialog(this, "Số điện thoại chỉ được nhập tối đa 10 chữ số!",
                    "Thông báo", JOptionPane.WARNING_MESSAGE);
            txtDienThoai.requestFocus();
            return;
        }
        KhachHang kh = new KhachHang(maKH, tenKH, dienThoai);

        if (khDAO.insert(kh)) {
            JOptionPane.showMessageDialog(this, "Thêm khách hàng thành công!");
            loadTable();
            // chọn dòng vừa thêm
            index = listKH.size() - 1;
            tbQLKH.setRowSelectionInterval(index, index);
            showDetail(index);
        } else {
            JOptionPane.showMessageDialog(this, "Thêm thất bại, có thể mã khách hàng đã tồn tại!");
        }
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn khách hàng để xóa!");
            return;
        }
        String maKH = txtMaKH.getText().trim();

        // kiểm tra FK với hóa đơn
        if (khDAO.hasHoaDon(maKH)) {
            JOptionPane.showMessageDialog(this, "Khách hàng này vẫn có hóa đơn, không thể xóa!");
            return;
        }

        if (JOptionPane.showConfirmDialog(this, "Bạn có muốn xóa khách hàng này?", "Xác nhận", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION) {
            if (khDAO.delete(maKH)) {
                JOptionPane.showMessageDialog(this, "Xóa thành công!");
                loadTable();
                clearForm();
                row = -1;
            } else {
                JOptionPane.showMessageDialog(this, "Xóa thất bại!");
            }
        }

    }//GEN-LAST:event_btnXoaActionPerformed

